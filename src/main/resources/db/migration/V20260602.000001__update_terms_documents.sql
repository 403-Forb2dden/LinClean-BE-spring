4. 탈퇴 회원의 계정 정보, 저장한 링크, URL 분석 이력, 카테고리, 알림 및 디바이스 토큰 등 회원에게 연결된 데이터는 탈퇴일로부터 30일간 보관될 수 있으며, 보관 기간 경과 후 정기적으로 영구 삭제됩니다.
5. 관계 법령상 보관이 필요한 정보가 있는 경우 해당 법령에서 정한 기간 동안 보관할 수 있습니다.

## 제12조 (지식재산권)

1. 서비스 및 서비스에 포함된 소프트웨어, 화면 구성, 로고, 문구 등에 관한 권리는 운영팀 또는 정당한 권리자에게 귀속됩니다.
