5. "저장 링크"란 이용자가 서비스 내에서 저장한 URL, 제목, 설명, 카테고리 등 링크 관리 정보를 말합니다.

## 제4조 (약관의 게시와 개정)

1. 운영팀은 본 약관의 내용을 서비스 화면 또는 연결 화면을 통해 이용자가 확인할 수 있도록 게시합니다.
2. 운영팀은 관련 법령을 위반하지 않는 범위에서 본 약관을 개정할 수 있습니다.
3. 약관이 변경되는 경우 운영팀은 변경 내용, 시행일 및 변경 사유를 서비스 내 공지사항 또는 약관 화면을 통해 안내합니다.
4. 이용자가 변경된 약관에 동의하지 않는 경우 서비스 이용을 중단하고 회원 탈퇴를 요청할 수 있습니다.

## 제5조 (회원가입 및 로그인)

1. 서비스는 Clerk 및 Google OAuth 등 외부 인증 서비스를 이용하여 로그인 기능을 제공합니다.
2. 운영팀은 인증 서비스로부터 서비스 이용에 필요한 회원 식별 정보를 제공받거나 검증할 수 있습니다.
3. 이용자는 본인의 계정 정보를 안전하게 관리해야 하며, 계정의 부정 사용이 의심되는 경우 즉시 운영팀에 알려야 합니다.
4. 운영팀은 이미 탈퇴 처리된 계정 또는 서비스 운영상 제한이 필요한 계정에 대해 로그인을 제한할 수 있습니다.

## 제6조 (서비스의 내용)

운영팀은 이용자에게 다음 각 호의 기능을 제공합니다.

1. URL 입력 또는 공유를 통한 안전성 분석
2. 분석 결과, 점수, 요약 및 위험 사유 제공
3. 분석한 링크 저장, 제목 수정, 북마크, 카테고리 관리
4. 서비스 공지사항 및 이용 안내 제공
5. 그 밖에 운영팀이 서비스 개선을 위해 제공하는 기능

## 제7조 (URL 분석 결과의 성격과 한계)

1. 서비스의 URL 분석 결과는 이용자의 판단을 돕기 위한 참고 정보입니다.
2. 운영팀은 Google Safe Browsing, URLhaus, OpenAI 등 외부 서비스와 자체 분석 로직을 활용할 수 있으나, 모든 악성 URL 또는 위험 요소를 완전하게 탐지함을 보장하지 않습니다.
3. 안전으로 표시된 URL이라도 이후 사이트 내용이 변경되거나 새로운 위협이 발생할 수 있으며, 위험 또는 주의로 표시된 URL이라도 실제 위험 여부는 상황에 따라 달라질 수 있습니다.
4. 이용자는 분석 결과만을 근거로 중요한 거래, 결제, 개인정보 입력 등을 진행해서는 안 되며, 최종 판단과 책임은 이용자에게 있습니다.

## 제8조 (이용자의 의무)

이용자는 서비스를 이용할 때 다음 행위를 해서는 안 됩니다.

1. 타인의 계정 또는 인증 정보를 무단으로 사용하는 행위
2. 악성 URL, 불법 콘텐츠, 피싱 사이트 등을 유포하거나 이를 목적으로 서비스를 이용하는 행위
3. 서비스의 분석 시스템, 서버, 네트워크에 과도한 부하를 주는 행위
4. 자동화 도구 등을 이용하여 비정상적으로 대량 요청을 발생시키는 행위
5. 운영팀 또는 제3자의 지식재산권, 개인정보, 명예, 신용 등 권리를 침해하는 행위
6. 관련 법령 또는 본 약관을 위반하는 행위

## 제9조 (저장 링크 및 이용자 콘텐츠)

1. 이용자는 자신이 입력하거나 저장한 URL, 제목, 설명, 카테고리 정보에 대해 필요한 권리와 책임을 가집니다.
2. 운영팀은 서비스 제공, 분석 결과 표시, 링크 관리 기능 제공 및 서비스 안정성 확보를 위해 이용자가 입력한 정보를 처리할 수 있습니다.
3. 운영팀은 이용자가 저장한 정보가 법령 또는 본 약관을 위반하거나 서비스 안정성을 해칠 우려가 있다고 판단하는 경우 해당 정보의 이용을 제한할 수 있습니다.

## 제10조 (서비스의 변경, 중단 및 종료)

1. 운영팀은 서비스 개선, 시스템 점검, 장애 대응, 외부 서비스 제공자의 정책 변경 등 필요한 경우 서비스의 전부 또는 일부를 변경하거나 일시 중단할 수 있습니다.
2. 본 서비스는 캡스톤 프로젝트 결과물로 운영되므로, 운영팀 사정에 따라 서비스가 축소, 중단 또는 종료될 수 있습니다.
3. 서비스 종료가 예정된 경우 운영팀은 가능한 범위에서 사전에 서비스 내 공지사항 등을 통해 안내합니다.

## 제11조 (회원 탈퇴 및 이용계약 해지)

1. 회원은 앱 내 회원 탈퇴 기능을 통해 언제든지 서비스 이용계약 해지를 요청할 수 있습니다.
2. 운영팀은 회원 탈퇴 요청 즉시 해당 계정을 탈퇴 상태로 전환하고 서비스 이용을 제한합니다.
